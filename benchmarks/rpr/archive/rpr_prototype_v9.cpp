// rpr_prototype_v9.cpp
// High-throughput exact Relax-Project-Refine solver for Admissible Rooted Partitioning.
// C++20, Linux. Recommended:
//   g++ -O3 -march=native -DNDEBUG -fopenmp -std=c++20 rpr_prototype_v9.cpp -o rpr_prototype_v9
//
// Active V8 execution model:
//   * Fixed CSR + distance-1 coloring are built once.
//   * Relax is an exact full color sweep every outer.  This deliberately prefers
//     cheap degree-40 CSR streaming over the heavy V7 histogram/version cache.
//   * Per-vertex neighbor-community aggregation uses a tiny thread-local L1 hash
//     table when max degree <= 64; high-degree graphs fall back to the dense counter.
//   * internalDeg + inverse membership are materialized only after the first Relax,
//     immediately before the first Project, then maintained incrementally.
//   * Project runs only on changed communities.
//   * Legal uses exact dynamic pending bits.  After every accepted color batch,
//     N(moved) and root(c) U N(root(c)) for size/root-changed communities are marked
//     immediately; later colors consume those marks in the same sweep.  Past colors
//     remain pending for the next Legal sweep.  This matches full-color sweep semantics
//     without scanning all nodes' adjacency.
//   * Community-size, membership and internalDeg conflicting writes use owner-computes.
//   * T/P are exact online; outer acceptance uses exact integer J_lambda comparison.
//
// Options:
//   --outer K              RPR outer rounds, default 5
//   --relaxed-sweeps K     Relax sweeps per outer, default 1
//   --legal-sweeps K       total Legal sweeps on final outer; earlier outers do 1
//   --init desc|asc|local|all   default desc
//   --lambda A/B           precision--recall trade-off, default 1/2
//   --full-legal           force every Legal sweep to scan all nodes (A/B reference)
//   --full-relax           compatibility flag; V8 Relax is already exact full streaming
//   --text-output          write "node root" text; default binary uint32 roots
//   --verify-audit         full-edge T/P + persistent-state verification after each outer
//
