ExactRatio parse_unit_exact_ratio(
    const std::string& text,
    const char* parameter_name) {
    try {
        const auto parsed = lstar::parse_lambda_ratio(text);
        return {parsed.numerator, parsed.denominator};
    } catch (const std::exception& error) {
        throw std::invalid_argument(
            std::string(parameter_name) + ": " + error.what());
    }
}

const char* to_string(TerminationReason reason) noexcept {
    switch (reason) {
        case TerminationReason::no_strict_improvement:
            return "no_strict_improvement";
        case TerminationReason::min_delta_reached:
            return "min_delta_reached";
        case TerminationReason::max_epochs_reached:
            return "max_epochs_reached";
        case TerminationReason::objective_undefined_no_reference_edges:
            return "objective_undefined_no_reference_edges";
        case TerminationReason::objective_undefined_no_admissible_pairs:
            return "objective_undefined_no_admissible_pairs";
    }
    return "unknown";
}

PartitionResult partition(
    SparseProblemView problem,
    const SolverConfig& config) {
    validate_solver_inputs(problem, config);
    const ExactRatio parsed_lambda = parse_unit_exact_ratio(
        config.recall_weight, "recall_weight");
    const ExactRatio parsed_min_delta = parse_unit_exact_ratio(
        config.min_delta, "min_delta");
    const lstar::LambdaRatio lambda{
        parsed_lambda.numerator, parsed_lambda.denominator};
    const lstar::LambdaRatio min_delta{
        parsed_min_delta.numerator, parsed_min_delta.denominator};

#ifdef _OPENMP
    omp_set_num_threads(static_cast<int>(config.threads));
#endif

    auto graph = lstar::Graph::view(problem);
    if (problem.reference_edges == 0) {
        return make_singleton_result(
            problem,
            config,
            parsed_lambda,
            parsed_min_delta,
            TerminationReason::objective_undefined_no_reference_edges);
    }
    const bool has_admissible_pair = std::any_of(
        problem.arc_admissibility.begin(),
        problem.arc_admissibility.end(),
        [](std::uint8_t value) { return (value & 1u) != 0; });
    if (!has_admissible_pair && parsed_lambda.numerator == 0) {
        return make_singleton_result(
            problem,
            config,
            parsed_lambda,
            parsed_min_delta,
            TerminationReason::objective_undefined_no_admissible_pairs);
    }

    lstar::Solver solver(graph, lambda, false);
    solver.initialize(config.initialization);
    solver.solve(config.max_epochs, min_delta);
    solver.verify_final_partition();

    std::vector<NodeId> representative_of(problem.node_count());
    std::vector<std::uint8_t> is_representative(problem.node_count(), 0);
    for (NodeId node = 0; node < problem.node_count(); ++node) {
        representative_of[node] = solver.representative_of(node);
        is_representative[solver.representative_of(node)] = 1;
    }
    std::vector<NodeId> representatives;
    representatives.reserve(problem.node_count());
    for (NodeId node = 0; node < problem.node_count(); ++node) {
        if (is_representative[node]) representatives.push_back(node);
    }

    const auto raw_audit = solver.current_audit();
    const auto final_metrics = solver.current_metrics();
    const auto termination_reason = solver.termination_reason();
    PartitionAudit audit{
        .recall_weight = parsed_lambda,
        .reference_edges = problem.reference_edges,
        .true_positive_edges = raw_audit.T,
        .predicted_pairs = raw_audit.P,
        .objective = final_metrics.objective,
        .precision = final_metrics.precision,
        .recall = final_metrics.recall,
        .f1 = final_metrics.f1};
    SolverStatistics statistics{
        .rounds = solver.rounds(),
        .termination_reason = termination_reason};
    return {
        .representatives = std::move(representatives),
        .representative_of = std::move(representative_of),
        .audit = std::move(audit),
        .provenance = make_provenance(
            config,
            parsed_min_delta,
            solver.selected_initialization(),
            termination_reason),
        .statistics = std::move(statistics)};
}

