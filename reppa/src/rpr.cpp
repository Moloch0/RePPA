// Production adaptation of legal_star_rpr_final_v9.cpp.
// High-throughput exact Relax-Project-Refine solver for Legal-Star Partitioning,
// driven directly by the repository's validated symmetric working CSR.
//
// Active V8 execution model:
//   * Fixed CSR + distance-1 coloring are built once.
//   * Relax is an exact full color sweep every epoch.  This deliberately prefers
//     cheap degree-40 CSR streaming over the heavy V7 histogram/version cache.
//   * Per-vertex neighbor-community aggregation uses a tiny thread-local L1 hash
//     table when degree <= 64; high-degree vertices use the dense counter.
//   * internalDeg + inverse membership are materialized only after the first Relax,
//     immediately before the first Project, then maintained incrementally.
//   * Project runs only on changed communities.
//   * Legal uses exact dynamic pending bits.  After every accepted color batch,
//     N(moved) and representative(c) U N(representative(c)) for size/representative-changed communities are marked
//     immediately; later colors consume those marks in the same sweep.  Past colors
//     remain pending for the next Legal sweep.  This matches full-color sweep semantics
//     without scanning all nodes' adjacency.
//   * Community-size, membership and internalDeg conflicting writes use owner-computes.
//   * T/P are exact online; epoch acceptance uses exact integer J_lambda comparison.
//
