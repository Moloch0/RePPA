struct ThreadScratch {
    static constexpr u32 SMALL_HASH_CAP = 128u;
    std::vector<u32> cntFlag;
    std::array<u32, SMALL_HASH_CAP> smallKey{};
    std::array<u32, SMALL_HASH_CAP> smallVal{};
    std::array<u32, SMALL_HASH_CAP> smallStamp{};
    u32 smallEpoch = 1;
    std::vector<u32> cands;
    // DDP-style owner-computes reduction buffers.  A proposal generated by
    // this thread appends (community, +/-1) to the vector owned by
    // community%numThreads.  After the proposal barrier, each owner thread
    // reduces all incoming vectors for its communities without atomics.
    std::vector<std::vector<std::pair<u32,i32>>> deltaByOwner;
    // Persistent-state commit routing. Producers append to the owner of the
    // source/destination community or target vertex; only that owner mutates
    // the corresponding linked-list / internal-degree state.
    std::vector<std::vector<u32>> memberRemoveByOwner;
    std::vector<std::vector<u32>> memberAddByOwner;
    std::vector<std::vector<std::pair<u32,i32>>> idegByOwner;
    std::vector<std::vector<u32>> dirtyByOwner;
    // Sparse dynamic-Legal queues. Each thread owns a contiguous vertex-ID
    // range; queues are separated by color. At color time owner-local queues
    // are sorted independently and concatenated by owner range, reproducing
    // the deterministic colorVerts order without scanning the whole color.
    std::vector<std::vector<u32>> legalPendingByColor;
    // Project changed-community routing/dedup.
    std::vector<std::vector<u32>> changedCommByOwner;
    std::vector<u32> changedOwned;
    std::vector<std::vector<u32>> peeledByOwner;
    std::vector<u32> peeledOwned;
    std::vector<u32> deltaTouched;
    std::vector<u32> emptyComms;
    // Sparse legal invalidation sources accumulated during one legal sweep.
    // movedVerts invalidate N(v); changedRepresentatives invalidate representative+N(representative).
    std::vector<u32> movedVerts;
    std::vector<u32> changedRepresentatives;
    std::vector<u32> peeledLocal;
    // Transaction undo logs. Each vertex/community is recorded at most once
    // per transaction using global epoch stamps.
    std::vector<std::pair<u32,u32>> partUndo;
    std::vector<std::pair<u32,u32>> representativeUndo;
    ThreadScratch() = default;
    ThreadScratch(u32 n, int nt, bool needDense) :
        deltaByOwner(static_cast<size_t>(nt)),
        memberRemoveByOwner(static_cast<size_t>(nt)),
        memberAddByOwner(static_cast<size_t>(nt)),
        idegByOwner(static_cast<size_t>(nt)),
        dirtyByOwner(static_cast<size_t>(nt)),
        changedCommByOwner(static_cast<size_t>(nt)),
        peeledByOwner(static_cast<size_t>(nt)) {
        if (needDense) cntFlag.resize(n);
        cands.reserve(256);
        deltaTouched.reserve(1024);
        emptyComms.reserve(256);
        movedVerts.reserve(1024);
        changedRepresentatives.reserve(1024);
        peeledLocal.reserve(1024);
        partUndo.reserve(4096);
        representativeUndo.reserve(2048);
        for (auto& b : deltaByOwner) b.reserve(256);
        for (auto& b : memberRemoveByOwner) b.reserve(256);
        for (auto& b : memberAddByOwner) b.reserve(256);
        for (auto& b : idegByOwner) b.reserve(1024);
        for (auto& b : dirtyByOwner) b.reserve(2048);
        for (auto& b : changedCommByOwner) b.reserve(1024);
        changedOwned.reserve(1024);
        for (auto& b : peeledByOwner) b.reserve(1024);
        peeledOwned.reserve(1024);
    }
};
static inline double sec_now() {
    using clock = std::chrono::steady_clock;
    static const auto t0 = clock::now();
    return std::chrono::duration<double>(clock::now() - t0).count();
}

struct Graph {
    u32 n = 0;
    u64 m = 0;
    const u64* off = nullptr;
    const u32* adj = nullptr;
    const std::uint8_t* admissibility = nullptr;
    static Graph view(reppa::SparseProblemView csr) {
        if (csr.node_count() > std::numeric_limits<u32>::max() ||
            csr.offsets.empty() || csr.offsets.front() != 0 ||
            csr.offsets.back() != csr.nodes.size() ||
            csr.arc_admissibility.size() != csr.nodes.size() ||
            !std::is_sorted(csr.offsets.begin(), csr.offsets.end()) ||
            csr.nodes.size() % 2 != 0 ||
            csr.reference_edges != csr.nodes.size() / 2) {
            throw std::invalid_argument(
                "RPR solver received an incompatible symmetric CSR");
        }
        for (std::size_t source = 0; source < csr.node_count(); ++source) {
            u32 previous = INVALID;
            for (u64 edge = csr.offsets[source];
                 edge < csr.offsets[source + 1]; ++edge) {
                const u32 target = csr.nodes[edge];
                if (target >= csr.node_count() ||
                    target == source ||
                    (previous != INVALID && target <= previous) ||
                    (csr.arc_admissibility[edge] & ~std::uint8_t{3}) != 0) {
                    throw std::invalid_argument(
                        "RPR solver received an invalid sparse graph arc");
                }
                previous = target;

                const auto reverse_begin =
                    csr.nodes.begin() + csr.offsets[target];
                const auto reverse_end =
                    csr.nodes.begin() + csr.offsets[target + 1];
                const auto reverse = std::lower_bound(
                    reverse_begin, reverse_end, static_cast<u32>(source));
                if (reverse == reverse_end || *reverse != source) {
                    throw std::invalid_argument(
                        "RPR reference graph CSR must be symmetric");
                }
                const auto reverse_index = static_cast<std::size_t>(
                    reverse - csr.nodes.begin());
                const std::uint8_t expected_reverse =
                    static_cast<std::uint8_t>(
                        ((csr.arc_admissibility[edge] & 1u) << 1) |
                        ((csr.arc_admissibility[edge] & 2u) >> 1));
                if (csr.arc_admissibility[reverse_index] != expected_reverse) {
                    throw std::invalid_argument(
                        "RPR admissibility bits disagree across reverse arcs");
                }
            }
        }
        const auto node_count = static_cast<u32>(csr.node_count());
        Graph g;
        g.n = node_count;
        g.m = csr.reference_edges;
        g.off = csr.offsets.data();
        g.adj = csr.nodes.data();
        g.admissibility = csr.arc_admissibility.data();
        return g;
    }

    inline u64 degree(u32 v) const noexcept { return off[v + 1] - off[v]; }
    inline bool source_can_represent(u64 edge) const noexcept {
        return (admissibility[edge] & 1u) != 0;
    }
    inline bool neighbor_can_represent(u64 edge) const noexcept {
        return (admissibility[edge] & 2u) != 0;
    }
    bool can_represent(u32 representative, u32 member) const noexcept {
        if (representative == member) return true;
        for (u64 edge = off[representative]; edge < off[representative + 1]; ++edge) {
            if (adj[edge] == member) return source_can_represent(edge);
        }
        return false;
    }
};

struct Audit {
    u64 T = 0;
    u64 P = 0;
};

struct LambdaRatio {
    u64 numerator = 1;
    u64 denominator = 2;

    [[nodiscard]] u64 precision_weight() const noexcept {
        return denominator - numerator;
    }
};

struct ObjectiveAnchor {
    // For lambda=a/b:
    //   gamma = (b-a)T / [a*m + (b-a)P].
    // Move gains use dT*penaltyDen - penaltyNum*dP exactly.
    u64 penaltyNum = 0;
    u64 penaltyDen = 1;
};

struct Seed {
    std::vector<u32> part;
    std::vector<u32> size;
    Audit a;
    std::string name;
};

class Solver {
public:
    explicit Solver(const Graph& graph, LambdaRatio lambda_ratio, bool verbose_output)
        : g(graph), n(graph.n), lambda(lambda_ratio), verbose(verbose_output) {
        validate_objective_range();
        workPart.resize(n);
        workSize.resize(n);
        workRepresentative.resize(n, INVALID);
        maxDegree = 0;
        for (u32 v = 0; v < n; ++v) maxDegree = std::max<u64>(maxDegree, g.degree(v));
#ifdef _OPENMP
        const int nt = omp_get_max_threads();
#else
        const int nt = 1;
#endif
        tls.reserve(static_cast<size_t>(nt));
        const bool needDense = maxDegree > ThreadScratch::SMALL_HASH_CAP / 2u;
        for (int i = 0; i < nt; ++i) tls.emplace_back(n, nt, needDense);
        threadBatchDT.resize(static_cast<size_t>(nt));
        threadBatchMoveCount.resize(static_cast<size_t>(nt));
        threadBatchDP.resize(static_cast<size_t>(nt));
        threadBatchValid.resize(static_cast<size_t>(nt));
        threadSingletonCount.resize(static_cast<size_t>(nt));
        threadSingletonBase.resize(static_cast<size_t>(nt));
        propDest.resize(n, INVALID);
        propSrc.resize(n, INVALID);
        propActualDst.resize(n, INVALID);
        propSrcCnt.resize(n);
        propDstCnt.resize(n);
        propSingletonRank.resize(n);
        batchDelta.resize(n, 0);
        batchMark.resize(n, 0);
        legalPending.resize(n, 0);
        peeledVerts.reserve(n / 64 + 1024);
        internalDeg.resize(n);
        keep.resize(n);
        projBestDeg.resize(n);
        projRepresentative.resize(n, INVALID);
        partTxnStamp.resize(n, 0);
        representativeTxnStamp.resize(n, 0);
        memberHead.resize(n, INVALID);
        memberNext.resize(n, INVALID);
        memberPrev.resize(n, INVALID);
        changedCommStamp.resize(n, 0);
    }

    void initialize(const std::string& init_mode) {
        double t0 = sec_now();
        std::vector<u32> order;
        if (init_mode == "desc" || init_mode == "asc") {
            order.resize(n);
            // Sparse graphs usually have modest max degree. Stable counting sort is
            // O(n+maxDegree), preserves vertex-id order inside equal-degree buckets,
            // and avoids millions of comparator-driven random offset loads.
            if (maxDegree <= 4000000ull) {
                std::vector<u32> pos(static_cast<size_t>(maxDegree) + 1, 0);
                for (u32 v = 0; v < n; ++v) ++pos[static_cast<u32>(g.degree(v))];
                u32 acc = 0;
                for (u64 dd = maxDegree + 1; dd-- > 0;) {
                    u32 cnt = pos[static_cast<size_t>(dd)];
                    pos[static_cast<size_t>(dd)] = acc;
                    acc += cnt;
                }
                for (u32 v = 0; v < n; ++v) {
                    u32 d = static_cast<u32>(g.degree(v));
                    order[pos[d]++] = v;
                }
            } else {
                std::iota(order.begin(), order.end(), 0u);
                std::sort(order.begin(), order.end(), [&](u32 a, u32 b) {
                    u64 da = g.degree(a), db = g.degree(b);
                    if (da != db) return da > db;
                    return a < b;
                });
            }
        }

        Seed seed = init_mode == "desc"
            ? make_greedy(order, false, "desc")
            : init_mode == "asc"
                ? make_greedy(order, true, "asc")
                : make_local_max();
        seed.a = audit(seed.part, seed.size);
        if (!objective_defined(seed.a)) {
            seed = make_single_edge_seed();
            seed.a = audit(seed.part, seed.size);
        }
        if (verbose) std::cerr << "seed " << seed.name << ": T=" << seed.a.T
                  << " P=" << seed.a.P
                  << " J_lambda=" << objective_value(seed.a)
                  << " F1=" << f1(seed.a) << "\n";
        if (!objective_defined(seed.a))
            throw std::runtime_error("J_lambda is undefined for initialization seed");
        workPart = std::move(seed.part);
        workSize = std::move(seed.size);
        workRepresentative.assign(n, INVALID);
        for (u32 c = 0; c < n; ++c) if (workSize[c]) workRepresentative[c] = c; // seed IDs are representative IDs
        workAudit = seed.a;
        rebuild_free_ids();
        build_coloring();
        for (auto& sc : tls) sc.legalPendingByColor.resize(numColors);
        selectedInitialization = seed.name;
        if (verbose) std::cerr << "chosen seed=" << selectedInitialization << " colors=" << numColors
                  << " init_time=" << (sec_now() - t0) << " s\n";
    }

    void solve(u32 max_epochs, LambdaRatio min_delta) {
        // Every epoch is exactly Relax -> Project -> Legal -> exact acceptance.
        // Search stops at max_epochs, on non-improvement, or after accepting a
        // positive gain below min_delta.  A final Legal-only refinement then
        // repeats with a fresh anchor per sweep under the same delta threshold.
        disable_legal_frontier();

        for (u32 epoch = 0; epoch < max_epochs; ++epoch) {
            const double t0 = sec_now();
            const Audit startAudit = workAudit;
            const ObjectiveAnchor anchor = make_anchor(startAudit);
            begin_transaction();
            if (verbose) std::cerr << "epoch=" << epoch
                      << " start T=" << workAudit.T << " P=" << workAudit.P
                      << " J_lambda=" << objective_value(workAudit)
                      << " F1=" << f1(workAudit)
                      << " relax_active=" << static_cast<u64>(n)
                      << "\n";

            //------------------------------- Relax -------------------------------
            // The first seed->solution relocation is intentionally allowed to
            // change a macroscopic fraction of vertices. Routing every moved edge
            // through owner queues is then more expensive than one parallel cache
            // rebuild. The cache still exists before Relax; only its maintenance
            // mode switches adaptively for this high-churn first epoch.
            deferPersistentUpdates = (epoch == 0);
            const double tr0 = sec_now();
            const u64 movedR = local_move_sweep(
                false, anchor.penaltyNum, anchor.penaltyDen,
                (epoch & 1) != 0);
            const double tr1 = sec_now();
            const double tp0 = sec_now();
            if (deferPersistentUpdates) {
                deferPersistentUpdates = false;
                build_internal_cache();
            }

            //------------------------------ Project ------------------------------
            project_to_stars_cached(false);
            const size_t changedBeforeProject = changedComms.size();
            const double tp1 = sec_now();

            //------------------------------- Legal -------------------------------
            // Dynamic pending is exact/conservative and automatically expands
            // to the full vertex set when transaction changes are dense.
            legalDynamicMode = true;
            seed_dynamic_legal_pending_from_transaction();
            const double tl0 = sec_now();
            const u64 movedL = local_move_sweep(
                true, anchor.penaltyNum, anchor.penaltyDen,
                (epoch & 1) == 0);
            const double tl1 = sec_now();

            const bool accept = objective_better(workAudit, startAudit);
            if (verbose) std::cerr << "  epoch_summary relax=" << (tr1-tr0)
                      << " project=" << (tp1-tp0)
                      << " legal=" << (tl1-tl0)
                      << " relax_moves=" << movedR
                      << " legal_moves=" << movedL
                      << " changed_comms=" << changedBeforeProject
                      << " peeled=" << lastPeeled
                      << " T=" << workAudit.T << " P=" << workAudit.P
                      << " J_lambda=" << objective_value(workAudit)
                      << " F1=" << f1(workAudit)
                      << " accept=" << (accept ? 1 : 0)
                      << " epoch_time=" << (sec_now()-t0) << " s\n";

            reppa::RoundStatistics round;
            round.round = static_cast<std::uint32_t>(roundStatistics.size());
            round.candidate = metrics(workAudit);
            round.relax_wall_ns = wall_ns(tr1 - tr0);
            round.project_wall_ns = wall_ns(tp1 - tp0);
            round.legal_wall_ns = wall_ns(tl1 - tl0);
            round.total_wall_ns = wall_ns(sec_now() - t0);
            round.accepted = accept;
            roundStatistics.push_back(round);

            if (accept) {
                const bool continue_search =
                    objective_gain_at_least(workAudit, startAudit, min_delta);
                commit_transaction();
                terminationReason =
                    reppa::TerminationReason::max_epochs_reached;
                if (!continue_search) {
                    terminationReason =
                        reppa::TerminationReason::min_delta_reached;
                    break;
                }
            } else {
                rollback_transaction(startAudit);
                // Membership/internalDeg were updated in-place during the rejected
                // transaction. Rebuild only on this rare terminal rollback path.
                internalReady = false;
                build_internal_cache();
                terminationReason = reppa::TerminationReason::no_strict_improvement;
                break;
            }
        }

        refine_legal(min_delta);
    }

    [[nodiscard]] u32 representative_of(u32 vertex) const {
        return workRepresentative[workPart[vertex]];
    }

    [[nodiscard]] const Audit& current_audit() const noexcept {
        return workAudit;
    }

    [[nodiscard]] reppa::Metrics current_metrics() const {
        return metrics(workAudit);
    }

    [[nodiscard]] const std::vector<reppa::RoundStatistics>&
    rounds() const noexcept {
        return roundStatistics;
    }

    [[nodiscard]] reppa::TerminationReason
    termination_reason() const noexcept {
        return terminationReason;
    }

    [[nodiscard]] const std::string& selected_initialization() const noexcept {
        return selectedInitialization;
    }

    void verify_final_partition() const {
        for (u32 v = 0; v < n; ++v) {
            const u32 representative = representative_of(v);
            if (representative >= n) throw std::runtime_error("partition representative is out of range");
            if (representative == v) continue;
            if (!g.can_represent(representative, v)) {
                throw std::runtime_error(
                    "partition contains a non-admissible representative/member assignment");
            }
        }
        const Audit exact = audit(workPart, workSize);
        if (exact.T != workAudit.T || exact.P != workAudit.P) {
            throw std::runtime_error("final partition T/P audit mismatch");
        }
    }

private:
    const Graph& g;
    const u32 n;
    const LambdaRatio lambda;
    const bool verbose;
    std::string selectedInitialization;
    std::vector<reppa::RoundStatistics> roundStatistics;
    reppa::TerminationReason terminationReason{
        reppa::TerminationReason::max_epochs_reached};

    // Single persistent accepted/current state. Successful epochs mutate
    // this state in place; speculative changes are protected by sparse undo logs.
    std::vector<u32> workPart, workSize, workRepresentative;
    Audit workAudit; // exact incremental T/P for the current state

    // Proper graph coloring makes each color class an independent set.  The hot
    // relocation path therefore evaluates one color in parallel. Community-size
    // interaction is handled by an exact sparse owner-computes batch reduction.
    u64 maxDegree = 0;
    std::vector<u32> colorOf, colorOff, colorVerts;
    std::vector<u32> colorWorkOffForward, colorWorkOffReverse;
    u32 numColors = 0;
    std::vector<ThreadScratch> tls;
    std::vector<i64> threadBatchDT;
    std::vector<u64> threadBatchMoveCount;
    std::vector<i128> threadBatchDP;
    std::vector<uint8_t> threadBatchValid;
    std::vector<u64> threadSingletonCount, threadSingletonBase;
    std::vector<u32> propDest, propSrc, propActualDst, propSrcCnt, propDstCnt;
    std::vector<u32> propSingletonRank;

    // Color-batch reduction state. batchDelta[c] is the net size change of
    // community c for all proposals in the current independent-set color.
    // Only touched communities are scanned/reset.
    std::vector<i64> batchDelta;
    std::vector<u32> batchMark;
    u32 batchEpoch = 1;
    u64 batchSingletonCounter = 0;

    std::vector<u32> freeIds;
    std::vector<uint8_t> legalPending;
    std::vector<u32> legalWorkVerts;
    bool legalDynamicMode = false;
    bool useLegalActive = false;
    u64 legalActiveCount = 0;
    u64 legalActiveEdges = 0;
    u64 lastPeeled = 0;

    std::vector<u32> internalDeg, projBestDeg, projRepresentative;
    std::vector<uint8_t> keep;
    std::vector<u32> peeledVerts;

    // Persistent first-order scalar cache used by Project. internalDeg[v] is
    // maintained across all epoch phases and equals d(v, part[v]).
    bool internalReady = false;
    bool deferPersistentUpdates = false;
    std::vector<u32> memberHead, memberNext, memberPrev;
    std::vector<u32> changedCommStamp, changedComms;
    u32 changedCommEpoch = 1;

    // Sparse transaction journal. Membership/representative values are recorded only on
    // their first modification in one transaction. Free IDs are maintained in
    // bulk on the forward path; the rare terminal rollback simply rebuilds them.
    std::vector<u32> partTxnStamp, representativeTxnStamp;
    u32 txnEpoch = 1;
    bool txnActive = false;

    static u64 wall_ns(double seconds) noexcept {
        if (seconds <= 0.0) return 0;
        return static_cast<u64>(seconds * 1000000000.0 + 0.5);
    }

    static reppa::ExactRatio reduced_ratio(u128 numerator, u128 denominator) {
        if (denominator == 0) throw std::logic_error("ratio denominator is zero");
        u128 left = numerator;
        u128 right = denominator;
        while (right != 0) {
            const u128 remainder = left % right;
            left = right;
            right = remainder;
        }
        const u128 divisor = left == 0 ? 1 : left;
        numerator /= divisor;
        denominator /= divisor;
        if (numerator > std::numeric_limits<u64>::max() ||
            denominator > std::numeric_limits<u64>::max()) {
            throw std::overflow_error("partition metric exceeds uint64 ratio range");
        }
        return {
            static_cast<u64>(numerator),
            static_cast<u64>(denominator)};
    }

    reppa::Metrics metrics(const Audit& value) const {
        reppa::Metrics result;
        const u64 denominator = objective_den(value);
        if (denominator != 0) {
            result.objective = reduced_ratio(
                static_cast<u128>(lambda.denominator) * value.T,
                denominator);
        }
        if (value.P != 0) result.precision = reduced_ratio(value.T, value.P);
        if (g.m != 0) result.recall = reduced_ratio(value.T, g.m);
        const u128 f1Denominator = static_cast<u128>(g.m) + value.P;
        if (f1Denominator != 0) {
            result.f1 = reduced_ratio(
                static_cast<u128>(2) * value.T, f1Denominator);
        }
        return result;
    }

    void begin_transaction() {
        ++txnEpoch;
        if (txnEpoch == 0) {
            std::fill(partTxnStamp.begin(), partTxnStamp.end(), 0);
            std::fill(representativeTxnStamp.begin(), representativeTxnStamp.end(), 0);
            txnEpoch = 1;
        }
        for (auto& sc : tls) {
            sc.partUndo.clear();
            sc.representativeUndo.clear();
        }
        txnActive = true;
    }

    inline void record_part_before_change(ThreadScratch& sc, u32 v) {
        if (!txnActive || partTxnStamp[v] == txnEpoch) return;
        partTxnStamp[v] = txnEpoch;
        sc.partUndo.push_back({v, workPart[v]});
    }

    inline void record_representative_before_change(ThreadScratch& sc, u32 c) {
        if (!txnActive || representativeTxnStamp[c] == txnEpoch) return;
        representativeTxnStamp[c] = txnEpoch;
        sc.representativeUndo.push_back({c, workRepresentative[c]});
    }

    inline void txn_free_push(u32 c) { freeIds.push_back(c); }

    inline u32 txn_free_pop() {
        if (freeIds.empty()) return INVALID;
        const u32 c = freeIds.back();
        freeIds.pop_back();
        return c;
    }

    void txn_free_shrink(size_t newSize) {
        if (newSize > freeIds.size()) throw std::runtime_error("invalid freeIds shrink");
        freeIds.resize(newSize);
    }

    u64 transaction_part_count() const {
        u64 x = 0;
        for (const auto& sc : tls) x += static_cast<u64>(sc.partUndo.size());
        return x;
    }

    void commit_transaction() {
        txnActive = false;
        for (auto& sc : tls) { sc.partUndo.clear(); sc.representativeUndo.clear(); }
    }

    void rollback_transaction(const Audit& auditBefore) {
        // Restore representatives and memberships. Each item appears once per transaction.
        for (auto& sc : tls) {
            for (auto it = sc.representativeUndo.rbegin(); it != sc.representativeUndo.rend(); ++it)
                workRepresentative[it->first] = it->second;
            for (auto it = sc.partUndo.rbegin(); it != sc.partUndo.rend(); ++it)
                workPart[it->first] = it->second;
        }
        // Sizes/free IDs are cheap to reconstruct only on the terminal/rare rollback path.
        std::fill(workSize.begin(), workSize.end(), 0);
        for (u32 v = 0; v < n; ++v) ++workSize[workPart[v]];
        rebuild_free_ids();
        workAudit = auditBefore;
        disable_legal_frontier();
        txnActive = false;
        for (auto& sc : tls) { sc.partUndo.clear(); sc.representativeUndo.clear(); }
    }

    void validate_objective_range() const {
        if (lambda.denominator == 0 || lambda.numerator > lambda.denominator)
            throw std::runtime_error("lambda must satisfy 0 <= numerator <= denominator");
        const u128 maxP = (n == 0)
            ? 0
            : static_cast<u128>(n) * static_cast<u128>(n - 1u) / 2u;
        const u128 precisionWeight = lambda.precision_weight();
        const u128 maxPenaltyNum = precisionWeight * static_cast<u128>(g.m);
        const u128 maxObjectiveDen = static_cast<u128>(lambda.numerator) * g.m
                                  + precisionWeight * maxP;
        const u128 maxU64 = std::numeric_limits<u64>::max();
        if (maxPenaltyNum > maxU64 || maxObjectiveDen > maxU64)
            throw std::runtime_error(
                "lambda weights are too large for the exact uint64 hot path");
    }

    inline u64 objective_den(const Audit& a) const {
        const u128 den = static_cast<u128>(lambda.numerator) * g.m
                       + static_cast<u128>(lambda.precision_weight()) * a.P;
        if (den > std::numeric_limits<u64>::max())
            throw std::runtime_error("objective denominator exceeds uint64");
        return static_cast<u64>(den);
    }

    inline bool objective_defined(const Audit& a) const {
        return objective_den(a) != 0;
    }

    inline ObjectiveAnchor make_anchor(const Audit& a) const {
        const u64 penaltyDen = objective_den(a);
        if (penaltyDen == 0)
            throw std::runtime_error(
                "J_lambda is undefined for the current partition");
        const u128 penaltyNum =
            static_cast<u128>(lambda.precision_weight()) * a.T;
        if (penaltyNum > std::numeric_limits<u64>::max())
            throw std::runtime_error("objective penalty numerator exceeds uint64");
        return ObjectiveAnchor{static_cast<u64>(penaltyNum), penaltyDen};
    }

    inline double objective_value(const Audit& a) const {
        const u64 den = objective_den(a);
        if (den == 0) return std::numeric_limits<double>::quiet_NaN();
        return static_cast<double>(lambda.denominator) * static_cast<double>(a.T) /
               static_cast<double>(den);
    }

    inline double f1(const Audit& a) const {
        return (a.T == 0) ? 0.0 : (2.0 * static_cast<double>(a.T) /
               (static_cast<double>(g.m) + static_cast<double>(a.P)));
    }

    inline bool objective_better(const Audit& a, const Audit& b) const {
        const u64 da = objective_den(a);
        const u64 db = objective_den(b);
        if (da == 0 || db == 0) return da != 0 && db == 0;
        // The common lambda.denominator factor in J_lambda cancels.
        return static_cast<u128>(a.T) * db > static_cast<u128>(b.T) * da;
    }

    inline bool objective_gain_at_least(
        const Audit& after,
        const Audit& before,
        const LambdaRatio& minimum) const {
        if (!objective_better(after, before)) return false;
        if (minimum.numerator == 0) return true;

        const cpp_int after_den = objective_den(after);
        const cpp_int before_den = objective_den(before);
        const cpp_int gain_numerator =
            cpp_int(lambda.denominator) *
            (cpp_int(after.T) * before_den -
             cpp_int(before.T) * after_den);
        const cpp_int gain_denominator = after_den * before_den;
        return gain_numerator * minimum.denominator >=
               cpp_int(minimum.numerator) * gain_denominator;
    }

    void refine_legal(const LambdaRatio& min_delta) {
        legalDynamicMode = true;
        seed_all_dynamic_legal_pending();

        for (;;) {
            const double t0 = sec_now();
            const Audit startAudit = workAudit;
            const ObjectiveAnchor anchor = make_anchor(startAudit);
            begin_transaction();
            const double tl0 = sec_now();
            const u64 moved = local_move_sweep(
                true,
                anchor.penaltyNum,
                anchor.penaltyDen,
                (roundStatistics.size() & 1u) == 0u);
            const double tl1 = sec_now();
            const bool accept = objective_better(workAudit, startAudit);

            reppa::RoundStatistics round;
            round.round = static_cast<std::uint32_t>(roundStatistics.size());
            round.candidate = metrics(workAudit);
            round.legal_wall_ns = wall_ns(tl1 - tl0);
            round.total_wall_ns = wall_ns(sec_now() - t0);
            round.accepted = accept;
            roundStatistics.push_back(round);

            if (!accept) {
                rollback_transaction(startAudit);
                internalReady = false;
                build_internal_cache();
                break;
            }

            const bool continue_refinement =
                objective_gain_at_least(workAudit, startAudit, min_delta);
            commit_transaction();
            if (verbose) {
                std::cerr << "  final_legal moved=" << moved
                          << " T=" << workAudit.T
                          << " P=" << workAudit.P
                          << " J_lambda=" << objective_value(workAudit)
                          << " continue=" << (continue_refinement ? 1 : 0)
                          << " time=" << (sec_now() - t0) << " s\n";
            }
            if (!continue_refinement) break;
            refresh_dynamic_legal_stats();
        }
    }

    Seed make_greedy(const std::vector<u32>& desc_order, bool reverse, std::string name) const {
        Seed s;
        s.name = std::move(name);
        s.part.assign(n, INVALID);
        s.size.assign(n, 0);
        auto visit = [&](u32 r) {
            if (s.part[r] != INVALID) return;
            s.part[r] = r;
            s.size[r] = 1;
            for (u64 e = g.off[r]; e < g.off[r + 1]; ++e) {
                u32 v = g.adj[e];
                if (s.part[v] == INVALID && g.source_can_represent(e)) {
                    s.part[v] = r;
                    ++s.size[r];
                }
            }
        };
        if (!reverse) {
            for (u32 r : desc_order) visit(r);
        } else {
            for (auto it = desc_order.rbegin(); it != desc_order.rend(); ++it) visit(*it);
        }
        return s;
    }

    inline bool higher_precedence(u32 a, u32 b) const noexcept {
        u64 da = g.degree(a), db = g.degree(b);
        return (da > db) || (da == db && a < b);
    }

    Seed make_local_max() const {
        Seed s;
        s.name = "local";
        s.part.assign(n, INVALID);
        s.size.assign(n, 0);
        std::vector<uint8_t> isRepresentative(n, 1);
#ifdef _OPENMP
#pragma omp parallel for schedule(static)
#endif
        for (i64 vv = 0; vv < static_cast<i64>(n); ++vv) {
            u32 v = static_cast<u32>(vv);
            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                u32 u = g.adj[e];
                if (higher_precedence(u, v)) { isRepresentative[v] = 0; break; }
            }
        }
#ifdef _OPENMP
#pragma omp parallel for schedule(static)
#endif
        for (i64 vv = 0; vv < static_cast<i64>(n); ++vv) {
            u32 v = static_cast<u32>(vv);
            if (isRepresentative[v]) { s.part[v] = v; continue; }
            u32 best = INVALID;
            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                u32 u = g.adj[e];
                if (isRepresentative[u] && g.neighbor_can_represent(e) &&
                    (best == INVALID || higher_precedence(u, best))) best = u;
            }
            s.part[v] = (best == INVALID ? v : best);
        }
        for (u32 v = 0; v < n; ++v) ++s.size[s.part[v]];
        return s;
    }

    Seed make_single_edge_seed() const {
        Seed s;
        s.name = "single_edge";
        s.part.resize(n);
        s.size.assign(n, 1);
        std::iota(s.part.begin(), s.part.end(), 0u);
        for (u32 left = 0; left < n; ++left) {
            for (u64 edge = g.off[left]; edge < g.off[left + 1]; ++edge) {
                const u32 right = g.adj[edge];
                if (left >= right) continue;
                const u32 representative = g.source_can_represent(edge)
                    ? left
                    : g.neighbor_can_represent(edge) ? right : INVALID;
                if (representative == INVALID) continue;
                const u32 member = representative == left ? right : left;
                s.part[member] = representative;
                s.size[member] = 0;
                s.size[representative] = 2;
                return s;
            }
        }
        throw std::logic_error(
            "reference graph has no admissible non-singleton assignment");
    }

    Audit audit(const std::vector<u32>& part, const std::vector<u32>& size) const {
        unsigned long long same = 0;
#ifdef _OPENMP
#pragma omp parallel for reduction(+:same) schedule(dynamic, 1024)
#endif
        for (i64 vv = 0; vv < static_cast<i64>(n); ++vv) {
            u32 v = static_cast<u32>(vv);
            u32 cv = part[v];
            u64 local = 0;
            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e)
                local += (part[g.adj[e]] == cv);
            same += local;
        }
        u64 P = 0;
        for (u32 c = 0; c < n; ++c) {
            u64 z = size[c];
            P += z * (z - 1) / 2;
        }
        return {static_cast<u64>(same / 2), P};
    }

    void build_coloring() {
        double t0 = sec_now();
        colorOf.assign(n, INVALID);
        std::vector<u32> seen(static_cast<size_t>(std::min<u64>(maxDegree + 2, static_cast<u64>(n) + 1)), 0);
        if (seen.size() < 2) seen.resize(2);
        u32 stamp = 1;
        u32 maxColor = 0;
        for (u32 v = 0; v < n; ++v) {
            ++stamp;
            if (stamp == 0) { std::fill(seen.begin(), seen.end(), 0); stamp = 1; }
            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                u32 u = g.adj[e];
                if (u >= v) continue;
                u32 c = colorOf[u];
                if (c != INVALID) seen[c] = stamp;
            }
            u32 c = 0;
            while (c < seen.size() && seen[c] == stamp) ++c;
            if (c == seen.size()) throw std::runtime_error("color scratch exhausted");
            colorOf[v] = c;
            maxColor = std::max(maxColor, c);
        }
        numColors = n ? maxColor + 1 : 0;
        colorOff.assign(static_cast<size_t>(numColors) + 1, 0);
        for (u32 v = 0; v < n; ++v) ++colorOff[colorOf[v] + 1];
        for (u32 c = 0; c < numColors; ++c) colorOff[c + 1] += colorOff[c];
        colorVerts.resize(n);
        std::vector<u32> cur(colorOff.begin(), colorOff.end() - 1);
        for (u32 v = 0; v < n; ++v) colorVerts[cur[colorOf[v]]++] = v;
        build_color_work_partitions();
        if (verbose) std::cerr << "coloring colors=" << numColors << " time=" << (sec_now() - t0) << " s\n";
    }

    void build_color_work_partitions() {
        const size_t threadCount = std::max<size_t>(1, tls.size());
        const size_t stride = threadCount + 1;
        colorWorkOffForward.assign(static_cast<size_t>(numColors) * stride, 0);
        colorWorkOffReverse.assign(static_cast<size_t>(numColors) * stride, 0);

        for (u32 color = 0; color < numColors; ++color) {
            const u32 begin = colorOff[color];
            const u32 finish = colorOff[color + 1];
            const u32 count = finish - begin;
            auto partition = [&](std::vector<u32>& offsets, bool reverse) {
                const size_t base = static_cast<size_t>(color) * stride;
                offsets[base] = 0;
                offsets[base + threadCount] = count;
                u64 totalWork = 0;
                for (u32 jj = 0; jj < count; ++jj) {
                    const u32 pos = reverse ? finish - 1u - jj : begin + jj;
                    totalWork += g.degree(colorVerts[pos]) + 1u;
                }
                size_t nextThread = 1;
                u64 completedWork = 0;
                for (u32 jj = 0; jj <= count && nextThread < threadCount; ++jj) {
                    while (nextThread < threadCount &&
                           static_cast<u128>(completedWork) * threadCount >=
                               static_cast<u128>(totalWork) * nextThread) {
                        offsets[base + nextThread] = jj;
                        ++nextThread;
                    }
                    if (jj == count) break;
                    const u32 pos = reverse ? finish - 1u - jj : begin + jj;
                    completedWork += g.degree(colorVerts[pos]) + 1u;
                }
                while (nextThread < threadCount) {
                    offsets[base + nextThread] = count;
                    ++nextThread;
                }
            };
            partition(colorWorkOffForward, false);
            partition(colorWorkOffReverse, true);
        }
    }

    [[nodiscard]] std::pair<u32, u32> color_work_range(
        u32 color,
        u32 count,
        bool reverse,
        int tid,
        int nt,
        bool dynamicWork) const noexcept {
        if (!dynamicWork && nt > 0 &&
            static_cast<size_t>(nt) == tls.size()) {
            const size_t stride = tls.size() + 1;
            const size_t base = static_cast<size_t>(color) * stride;
            const auto& offsets = reverse
                ? colorWorkOffReverse
                : colorWorkOffForward;
            return {
                offsets[base + static_cast<size_t>(tid)],
                offsets[base + static_cast<size_t>(tid) + 1]};
        }
        const u32 base = count / static_cast<u32>(nt);
        const u32 remainder = count % static_cast<u32>(nt);
        const u32 thread = static_cast<u32>(tid);
        const u32 rangeBegin =
            thread * base + std::min(thread, remainder);
        const u32 rangeEnd = rangeBegin + base + (thread < remainder ? 1u : 0u);
        return {rangeBegin, rangeEnd};
    }

    void rebuild_free_ids() {
        freeIds.clear();
        freeIds.reserve(n);
        for (u32 c = 0; c < n; ++c) if (workSize[c] == 0) freeIds.push_back(c);
    }

    inline int range_owner(u32 x, int nt) const {
        if (nt <= 1 || n == 0) return 0;
        u64 o = (static_cast<u64>(x) * static_cast<u64>(nt)) / static_cast<u64>(n);
        if (o >= static_cast<u64>(nt)) o = static_cast<u64>(nt - 1);
        return static_cast<int>(o);
    }

    inline void membership_remove_owned(u32 v, u32 src) {
        const u32 p = memberPrev[v], q = memberNext[v];
        if (p != INVALID) memberNext[p] = q; else memberHead[src] = q;
        if (q != INVALID) memberPrev[q] = p;
        memberPrev[v] = INVALID;
        memberNext[v] = INVALID;
    }

    inline void membership_insert_owned(u32 v, u32 dst) {
        const u32 h = memberHead[dst];
        memberPrev[v] = INVALID;
        memberNext[v] = h;
        if (h != INVALID) memberPrev[h] = v;
        memberHead[dst] = v;
    }

    // Build inverse membership with the same persistent community ownership used
    // by runtime commits. Producers route vertices to owner(c); each owner alone
    // mutates the lists of its communities. No global linked-list serial pass.
    void build_membership() {
        std::fill(memberHead.begin(), memberHead.end(), INVALID);
        std::fill(memberNext.begin(), memberNext.end(), INVALID);
        std::fill(memberPrev.begin(), memberPrev.end(), INVALID);
#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
            const int nt = omp_get_num_threads();
#else
            const int tid = 0, nt = 1;
#endif
            ThreadScratch& sc = tls[static_cast<size_t>(tid)];
            for (int owner = 0; owner < nt; ++owner) sc.memberAddByOwner[static_cast<size_t>(owner)].clear();
#ifdef _OPENMP
#pragma omp for schedule(static)
#endif
            for (i64 vv = 0; vv < static_cast<i64>(n); ++vv) {
                const u32 v = static_cast<u32>(vv);
                const u32 c = workPart[v];
                sc.memberAddByOwner[static_cast<size_t>(c % static_cast<u32>(nt))].push_back(v);
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            for (int producer = 0; producer < nt; ++producer) {
                const auto& in = tls[static_cast<size_t>(producer)].memberAddByOwner[static_cast<size_t>(tid)];
                for (u32 v : in) membership_insert_owned(v, workPart[v]);
            }
        }
    }

    void build_internal_cache() {
        const double t0 = sec_now();
#ifdef _OPENMP
#pragma omp parallel for schedule(dynamic, 1024)
#endif
        for (i64 vv = 0; vv < static_cast<i64>(n); ++vv) {
            const u32 v = static_cast<u32>(vv);
            const u32 c = workPart[v];
            u32 d = 0;
            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) d += (workPart[g.adj[e]] == c);
            internalDeg[v] = d;
        }
        build_membership();
        internalReady = true;
        if (verbose) std::cerr << "internal-cache built time=" << (sec_now()-t0) << " s\n";
    }

    void collect_changed_communities_from_txn(bool allNonempty = false) {
        ++changedCommEpoch;
        if (changedCommEpoch == 0) {
#ifdef _OPENMP
#pragma omp parallel for schedule(static)
#endif
            for (i64 cc = 0; cc < static_cast<i64>(n); ++cc)
                changedCommStamp[static_cast<u32>(cc)] = 0;
            changedCommEpoch = 1;
        }
        changedComms.clear();

#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
            const int nt = omp_get_num_threads();
#else
            const int tid = 0, nt = 1;
#endif
            ThreadScratch& out = tls[static_cast<size_t>(tid)];
            out.changedOwned.clear();
            for (int owner = 0; owner < nt; ++owner)
                out.changedCommByOwner[static_cast<size_t>(owner)].clear();

            if (allNonempty) {
                const u32 lo = static_cast<u32>((static_cast<u64>(n) * tid) / nt);
                const u32 hi = static_cast<u32>((static_cast<u64>(n) * (tid + 1)) / nt);
                for (u32 c = lo; c < hi; ++c) {
                    if (!workSize[c]) continue;
                    changedCommStamp[c] = changedCommEpoch;
                    out.changedOwned.push_back(c);
                }
            } else {
                // Each transaction log already belongs to one producer thread.
                // Producers only route; the community-range owner is the sole
                // writer of changedCommStamp[c].
                const auto& in = tls[static_cast<size_t>(tid)].partUndo;
                auto emit = [&](u32 c) {
                    if (c == INVALID) return;
                    out.changedCommByOwner[static_cast<size_t>(range_owner(c, nt))].push_back(c);
                };
                for (const auto& rec : in) {
                    emit(rec.second);
                    emit(workPart[rec.first]);
                }
#ifdef _OPENMP
#pragma omp barrier
#endif
                for (int producer = 0; producer < nt; ++producer) {
                    const auto& q = tls[static_cast<size_t>(producer)].changedCommByOwner[static_cast<size_t>(tid)];
                    for (u32 c : q) {
                        if (changedCommStamp[c] == changedCommEpoch) continue;
                        changedCommStamp[c] = changedCommEpoch;
                        out.changedOwned.push_back(c);
                    }
                }
            }

            threadSingletonCount[static_cast<size_t>(tid)] = static_cast<u64>(out.changedOwned.size());
#ifdef _OPENMP
#pragma omp barrier
#pragma omp single
#endif
            {
                u64 total = 0;
                for (int t = 0; t < nt; ++t) {
                    threadSingletonBase[static_cast<size_t>(t)] = total;
                    total += threadSingletonCount[static_cast<size_t>(t)];
                }
                changedComms.resize(static_cast<size_t>(total));
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            const size_t base = static_cast<size_t>(threadSingletonBase[static_cast<size_t>(tid)]);
            std::copy(out.changedOwned.begin(), out.changedOwned.end(), changedComms.begin() + base);
        }
    }

    u64 local_move_sweep(
        bool legal, u64 penaltyNum, u64 penaltyDen, bool reverse) {
        static constexpr u32 REPRESENTATIVE_BIT = 0x80000000u;
        static constexpr u32 COUNT_MASK = 0x7fffffffu;
        static constexpr u32 NO_MOVE = INVALID;
        static constexpr u32 NEW_SINGLETON = INVALID - 1u;
        if (maxDegree > COUNT_MASK) throw std::runtime_error("degree exceeds scratch counter range");
        const i128 lim = static_cast<i128>(std::numeric_limits<i64>::max()) / 4;
        const bool fast64 = static_cast<i128>(penaltyDen) * static_cast<i128>(maxDegree) <= lim &&
                            static_cast<i128>(penaltyNum) * static_cast<i128>(n) <= lim;

        if (legal) {
            for (auto& sc : tls) {
                sc.movedVerts.clear();
                sc.changedRepresentatives.clear();
            }
        }

        unsigned long long moved = 0;
        i64 batchDT = 0;
        unsigned long long batchMoveCount = 0;
        i128 batchDP = 0;
        bool batchAccept = false;
        u64 batchFreeBase = 0;
        u32 currentEpoch = 0;
        int actualThreads = 1;
        const bool mergeLegalDirtyScan =
            legal && legalDynamicMode && internalReady &&
            !deferPersistentUpdates;

#ifdef _OPENMP
#pragma omp parallel reduction(+:moved)
#endif
        {
#ifdef _OPENMP
            int tid = omp_get_thread_num();
            int nt = omp_get_num_threads();
#else
            int tid = 0;
            int nt = 1;
#endif
            ThreadScratch& sc = tls[static_cast<size_t>(tid)];
#ifdef _OPENMP
#pragma omp single
#endif
            actualThreads = nt;

            for (u32 step = 0; step < numColors; ++step) {
                u32 color = reverse ? (numColors - 1 - step) : step;
                const std::vector<u32>* vertsPtr = nullptr;
                u32 begin = 0, finish = 0;

                if (legal && legalDynamicMode) {
                    // Sparse dependency-driven scheduling.  Every vertex belongs
                    // to the queue of its contiguous ID-range owner.  Owners sort
                    // independently; concatenating owner ranges exactly restores
                    // ascending vertex order inside this color without scanning
                    // colorVerts[color].
                    auto& q = sc.legalPendingByColor[color];
                    std::sort(q.begin(), q.end());
                    threadSingletonCount[static_cast<size_t>(tid)] = static_cast<u64>(q.size());
#ifdef _OPENMP
#pragma omp barrier
#pragma omp single
#endif
                    {
                        u64 total = 0;
                        for (int t = 0; t < actualThreads; ++t) {
                            threadSingletonBase[static_cast<size_t>(t)] = total;
                            total += threadSingletonCount[static_cast<size_t>(t)];
                        }
                        legalWorkVerts.resize(static_cast<size_t>(total));
                    }
                    const size_t qbase = static_cast<size_t>(threadSingletonBase[static_cast<size_t>(tid)]);
                    std::copy(q.begin(), q.end(), legalWorkVerts.begin() + qbase);
                    q.clear();
#ifdef _OPENMP
#pragma omp barrier
#endif
                    vertsPtr = &legalWorkVerts;
                    begin = 0;
                    finish = static_cast<u32>(legalWorkVerts.size());
                } else {
                    vertsPtr = &colorVerts;
                    begin = colorOff[color];
                    finish = colorOff[color + 1];
                }
                if (begin == finish) continue;
                const std::vector<u32>& verts = *vertsPtr;

#ifdef _OPENMP
#pragma omp single
#endif
                {
                    batchDT = 0;
                    batchMoveCount = 0;
                    batchDP = 0;
                    batchAccept = false;
                    batchSingletonCounter = 0;
                    ++batchEpoch;
                    if (batchEpoch == 0) {
                        std::fill(batchMark.begin(), batchMark.end(), 0);
                        batchEpoch = 1;
                    }
                    currentEpoch = batchEpoch;
                }
                for (int owner = 0; owner < nt; ++owner) sc.deltaByOwner[static_cast<size_t>(owner)].clear();
                sc.deltaTouched.clear();
                sc.emptyComms.clear();
                if (legal && legalDynamicMode) {
                    sc.movedVerts.clear();
                    sc.changedRepresentatives.clear();
                    for (int owner = 0; owner < nt; ++owner) {
                        sc.dirtyByOwner[static_cast<size_t>(owner)].clear();
                    }
                }
                u64 localSingletonCount = 0;
                i64 localBatchDT = 0;
                u64 localBatchMoveCount = 0;
                const u32 workCount = finish - begin;
                const auto [workBegin, workEnd] = color_work_range(
                    color, workCount, reverse, tid, nt,
                    legal && legalDynamicMode);

                for (u32 jj = workBegin; jj < workEnd; ++jj) {
                    u32 pos = reverse ? (finish - 1u - jj) : (begin + jj);
                    u32 v = verts[pos];
                    if (legal && legalDynamicMode) {
                        if (!legalPending[v]) { propDest[v] = NO_MOVE; propActualDst[v] = NO_MOVE; continue; }
                        // This color consumes the current pending reason. Changes
                        // committed by this or later colors may set it again for
                        // the next sweep.
                        legalPending[v] = 0;
                    }
                    u32 src = workPart[v];
                    u32 srcSize = workSize[src];
                    propDest[v] = NO_MOVE;
                    propActualDst[v] = NO_MOVE;
                    propSrc[v] = src;
                    if (legal && workRepresentative[src] == v && srcSize > 1) continue;

                    sc.cands.clear();
                    u32 srcCnt = 0;
                    const bool smallCounter = g.degree(v) <=
                        ThreadScratch::SMALL_HASH_CAP / 2u;
                    u32 hEpoch = 0;
                    if (smallCounter) {
                        ++sc.smallEpoch;
                        if (sc.smallEpoch == 0) { sc.smallStamp.fill(0); sc.smallEpoch = 1; }
                        hEpoch = sc.smallEpoch;
                    }
                    for (u64 e = g.off[v], ee = g.off[v + 1]; e < ee; ++e) {
                        const u32 u = g.adj[e];
                        const u32 c = workPart[u];
                        if (smallCounter) {
                            u32 h = (c * 2654435761u) & (ThreadScratch::SMALL_HASH_CAP - 1u);
                            while (sc.smallStamp[h] == hEpoch && sc.smallKey[h] != c)
                                h = (h + 1u) & (ThreadScratch::SMALL_HASH_CAP - 1u);
                            if (sc.smallStamp[h] != hEpoch) {
                                sc.smallStamp[h] = hEpoch; sc.smallKey[h] = c; sc.smallVal[h] = 0; sc.cands.push_back(h);
                            }
                            u32 x = sc.smallVal[h];
                            const u32 cnt = (x & COUNT_MASK) + 1u;
                            x = (x & REPRESENTATIVE_BIT) | cnt;
                            if (legal && workRepresentative[c] == u &&
                                g.neighbor_can_represent(e)) x |= REPRESENTATIVE_BIT;
                            sc.smallVal[h] = x;
                        } else {
                            u32 x = sc.cntFlag[c];
                            if ((x & COUNT_MASK) == 0) sc.cands.push_back(c);
                            const u32 cnt = (x & COUNT_MASK) + 1u;
                            x = (x & REPRESENTATIVE_BIT) | cnt;
                            if (legal && workRepresentative[c] == u &&
                                g.neighbor_can_represent(e)) x |= REPRESENTATIVE_BIT;
                            sc.cntFlag[c] = x;
                        }
                        srcCnt += (c == src);
                    }

                    u32 bestDest = NO_MOVE;
                    u32 bestCnt = 0;
                    bool positive = false;
                    if (fast64) {
                        i64 bestScore = std::numeric_limits<i64>::min();
                        if (srcSize > 1) { bestDest = NEW_SINGLETON; bestScore = 0; }
                        for (u32 key : sc.cands) {
                            const u32 c = smallCounter ? sc.smallKey[key] : key;
                            const u32 x = smallCounter ? sc.smallVal[key] : sc.cntFlag[c];
                            if (!smallCounter) sc.cntFlag[c] = 0;
                            if (c == src) continue;
                            if (legal && !(x & REPRESENTATIVE_BIT)) continue;
                            u32 dc = x & COUNT_MASK;
                            u32 sz = workSize[c];
                            if (sz == 0) continue;
                            i64 score = static_cast<i64>(static_cast<u64>(dc) * penaltyDen)
                                      - static_cast<i64>(penaltyNum * static_cast<u64>(sz));
                            if (score > bestScore || (score == bestScore && c < bestDest)) {
                                bestScore = score; bestDest = c; bestCnt = dc;
                            }
                        }
                        if (bestDest != NO_MOVE) {
                            u32 dstSize = (bestDest == NEW_SINGLETON) ? 0u : workSize[bestDest];
                            i64 dT = static_cast<i64>(bestCnt) - static_cast<i64>(srcCnt);
                            i64 dP = static_cast<i64>(dstSize) - static_cast<i64>(srcSize) + 1;
                            i64 gain = static_cast<i64>(dT * static_cast<i64>(penaltyDen))
                                     - static_cast<i64>(static_cast<i64>(penaltyNum) * dP);
                            positive = gain > 0;
                        }
                    } else {
                        i128 bestScore = -((static_cast<i128>(1)) << 120);
                        if (srcSize > 1) { bestDest = NEW_SINGLETON; bestScore = 0; }
                        for (u32 key : sc.cands) {
                            const u32 c = smallCounter ? sc.smallKey[key] : key;
                            const u32 x = smallCounter ? sc.smallVal[key] : sc.cntFlag[c];
                            if (!smallCounter) sc.cntFlag[c] = 0;
                            if (c == src) continue;
                            if (legal && !(x & REPRESENTATIVE_BIT)) continue;
                            u32 dc = x & COUNT_MASK;
                            u32 sz = workSize[c];
                            if (sz == 0) continue;
                            i128 score = static_cast<i128>(dc) * penaltyDen
                                       - static_cast<i128>(penaltyNum) * sz;
                            if (score > bestScore || (score == bestScore && c < bestDest)) {
                                bestScore = score; bestDest = c; bestCnt = dc;
                            }
                        }
                        if (bestDest != NO_MOVE) {
                            u32 dstSize = (bestDest == NEW_SINGLETON) ? 0u : workSize[bestDest];
                            i64 dT = static_cast<i64>(bestCnt) - static_cast<i64>(srcCnt);
                            i64 dP = static_cast<i64>(dstSize) - static_cast<i64>(srcSize) + 1;
                            i128 gain = static_cast<i128>(dT) * penaltyDen
                                      - static_cast<i128>(penaltyNum) * dP;
                            positive = gain > 0;
                        }
                    }
                    if (!positive) continue;

                    propDest[v] = bestDest;
                    propSrcCnt[v] = srcCnt;
                    propDstCnt[v] = bestCnt;
                    localBatchDT +=
                        static_cast<i64>(bestCnt) - static_cast<i64>(srcCnt);
                    ++localBatchMoveCount;

                    sc.deltaByOwner[static_cast<size_t>(src % static_cast<u32>(nt))].push_back({src, -1});
                    if (bestDest == NEW_SINGLETON) {
                        propSingletonRank[v] = localSingletonCount++;
                    } else {
                        sc.deltaByOwner[static_cast<size_t>(bestDest % static_cast<u32>(nt))].push_back({bestDest, +1});
                    }
                }

                threadBatchDT[static_cast<size_t>(tid)] = localBatchDT;
                threadBatchMoveCount[static_cast<size_t>(tid)] =
                    localBatchMoveCount;
                threadSingletonCount[static_cast<size_t>(tid)] = localSingletonCount;
#ifdef _OPENMP
#pragma omp barrier
#endif

                // Owner-computes sparse AllReduce: owner tid exclusively updates
                // communities c with c%nt==tid.  No per-move atomic size update.
                for (int srcTid = 0; srcTid < nt; ++srcTid) {
                    const auto& incoming = tls[static_cast<size_t>(srcTid)].deltaByOwner[static_cast<size_t>(tid)];
                    for (const auto& rec : incoming) {
                        u32 c = rec.first;
                        if (batchMark[c] != currentEpoch) {
                            batchMark[c] = currentEpoch;
                            batchDelta[c] = 0;
                            sc.deltaTouched.push_back(c);
                        }
                        batchDelta[c] += rec.second;
                    }
                }

                i128 localDP = 0;
                bool localValid = true;
                for (u32 c : sc.deltaTouched) {
                    i64 oldSize = static_cast<i64>(workSize[c]);
                    i64 newSize = oldSize + batchDelta[c];
                    if (newSize < 0 || newSize > static_cast<i64>(n)) { localValid = false; break; }
                    localDP += static_cast<i128>(newSize) * (newSize - 1) / 2
                             - static_cast<i128>(oldSize) * (oldSize - 1) / 2;
                }
                threadBatchDP[static_cast<size_t>(tid)] = localDP;
                threadBatchValid[static_cast<size_t>(tid)] = localValid ? 1 : 0;

#ifdef _OPENMP
#pragma omp barrier
#pragma omp single
#endif
                {
                    batchDT = 0;
                    batchMoveCount = 0;
                    i128 dp = 0;
                    for (int t = 0; t < actualThreads; ++t) {
                        batchDT += threadBatchDT[static_cast<size_t>(t)];
                        batchMoveCount +=
                            threadBatchMoveCount[static_cast<size_t>(t)];
                        dp += threadBatchDP[static_cast<size_t>(t)];
                    }
                    bool valid = batchMoveCount != 0;
                    for (int t = 0; t < actualThreads; ++t) {
                        valid = valid &&
                            (threadBatchValid[static_cast<size_t>(t)] != 0);
                    }
                    batchDP = dp; // fresh singletons contribute zero predicted pairs
                    u64 singletonTotal = 0;
                    for (int t = 0; t < actualThreads; ++t) {
                        threadSingletonBase[static_cast<size_t>(t)] = singletonTotal;
                        singletonTotal += threadSingletonCount[static_cast<size_t>(t)];
                    }
                    batchSingletonCounter = singletonTotal;
                    i128 gain = static_cast<i128>(batchDT) * penaltyDen
                              - static_cast<i128>(penaltyNum) * batchDP;
                    batchAccept = valid && gain > 0 && batchSingletonCounter <= freeIds.size();
                    if (batchAccept) batchFreeBase = static_cast<u64>(freeIds.size()) - batchSingletonCounter;
                }

                if (batchAccept) {
                    // Save legal size-dependency representatives before possibly emptying a source.
                    for (u32 c : sc.deltaTouched) {
                        i64 dc = batchDelta[c];
                        if (legal && dc != 0 && workRepresentative[c] != INVALID)
                            sc.changedRepresentatives.push_back(workRepresentative[c]);
                        workSize[c] = static_cast<u32>(static_cast<i64>(workSize[c]) + dc);
                        if (workSize[c] == 0) {
                            if (legal) {
                                record_representative_before_change(sc, c);
                                workRepresentative[c] = INVALID;
                            }
                            sc.emptyComms.push_back(c);
                        }
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                    for (u32 jj = workBegin; jj < workEnd; ++jj) {
                        u32 pos = reverse ? (finish - 1u - jj) : (begin + jj);
                        u32 v = verts[pos];
                        u32 dst = propDest[v];
                        if (dst == NO_MOVE) continue;
                        if (dst == NEW_SINGLETON) {
                            u64 globalRank = threadSingletonBase[static_cast<size_t>(tid)] + propSingletonRank[v];
                            u32 realDst = freeIds[static_cast<size_t>(batchFreeBase + globalRank)];
                            record_part_before_change(sc, v);
                            workPart[v] = realDst;
                            propActualDst[v] = realDst;
                            workSize[realDst] = 1;
                            if (legal) {
                                record_representative_before_change(sc, realDst);
                                workRepresentative[realDst] = v;
                                sc.changedRepresentatives.push_back(v);
                            }
                        } else {
                            record_part_before_change(sc, v);
                            workPart[v] = dst;
                            propActualDst[v] = dst;
                        }
                        if (legal) sc.movedVerts.push_back(v);
                    }
#ifdef _OPENMP
#pragma omp barrier
#pragma omp single
#endif
                    {
                        txn_free_shrink(static_cast<size_t>(batchFreeBase));
                        u64 emptyTotal = 0;
                        for (int t = 0; t < actualThreads; ++t) {
                            threadSingletonBase[static_cast<size_t>(t)] = emptyTotal;
                            emptyTotal += tls[static_cast<size_t>(t)].emptyComms.size();
                        }
                        freeIds.resize(static_cast<size_t>(batchFreeBase + emptyTotal));
                        workAudit.T = static_cast<u64>(static_cast<i128>(workAudit.T) + batchDT);
                        workAudit.P = static_cast<u64>(static_cast<i128>(workAudit.P) + batchDP);
                        moved += batchMoveCount;
                    }
                    {
                        const u64 base = batchFreeBase + threadSingletonBase[static_cast<size_t>(tid)];
                        for (size_t i = 0; i < sc.emptyComms.size(); ++i)
                            freeIds[static_cast<size_t>(base + i)] = sc.emptyComms[i];
                    }
                } else if (batchMoveCount != 0) {
                    // Rare exact fallback: if simultaneous interaction loses gain,
                    // linearize this color and recheck every move with current sizes.
#ifdef _OPENMP
#pragma omp single
#endif
                    {
#ifdef _OPENMP
                        ThreadScratch& serialSc = tls[static_cast<size_t>(omp_get_thread_num())];
#else
                        ThreadScratch& serialSc = tls[0];
#endif
                        auto commit_one = [&](u32 v) {
                            u32 dst = propDest[v];
                            if (dst == NO_MOVE) return;
                            u32 src = workPart[v];
                            u32 srcSize = workSize[src];
                            if (legal && workRepresentative[src] == v && srcSize > 1) return;
                            u32 dstSize = (dst == NEW_SINGLETON) ? 0u : workSize[dst];
                            if (dst != NEW_SINGLETON && dstSize == 0) return;
                            i64 dT = static_cast<i64>(propDstCnt[v]) - static_cast<i64>(propSrcCnt[v]);
                            i64 dP = static_cast<i64>(dstSize) - static_cast<i64>(srcSize) + 1;
                            i128 gain = static_cast<i128>(dT) * penaltyDen
                                      - static_cast<i128>(penaltyNum) * dP;
                            if (gain <= 0) return;

                            if (legal && workRepresentative[src] != INVALID) serialSc.changedRepresentatives.push_back(workRepresentative[src]);
                            if (legal && dst != NEW_SINGLETON && workRepresentative[dst] != INVALID)
                                serialSc.changedRepresentatives.push_back(workRepresentative[dst]);

                            u32 realDst = dst;
                            if (dst == NEW_SINGLETON) {
                                if (freeIds.empty()) return;
                                realDst = txn_free_pop();
                                workSize[realDst] = 0;
                            }
                            --workSize[src];
                            if (workSize[src] == 0) {
                                if (legal) {
                                    record_representative_before_change(serialSc, src);
                                    workRepresentative[src] = INVALID;
                                }
                                txn_free_push(src);
                            }
                            ++workSize[realDst];
                            record_part_before_change(serialSc, v);
                            workPart[v] = realDst;
                            propSrc[v] = src;
                            propActualDst[v] = realDst;
                            if (legal) {
                                if (dst == NEW_SINGLETON) {
                                    record_representative_before_change(serialSc, realDst);
                                    workRepresentative[realDst] = v;
                                    serialSc.changedRepresentatives.push_back(v);
                                }
                                serialSc.movedVerts.push_back(v);
                            }
                            workAudit.T = static_cast<u64>(static_cast<i128>(workAudit.T) + dT);
                            workAudit.P = static_cast<u64>(static_cast<i128>(workAudit.P) + dP);
                            ++moved;
                        };
                        if (!reverse) {
                            for (u32 pos = begin; pos < finish; ++pos) commit_one(verts[pos]);
                        } else {
                            for (u32 pos = finish; pos-- > begin;) commit_one(verts[pos]);
                        }
                    }
                }

                if (internalReady && !deferPersistentUpdates) {
#ifdef _OPENMP
#pragma omp barrier
#endif
                    // Route every accepted membership change and every additive
                    // internal-degree update to its unique persistent owner.
                    // Removal and insertion are separate phases because a moved
                    // vertex belongs to two community owners during the transition.
                    for (int owner = 0; owner < nt; ++owner) {
                        sc.memberRemoveByOwner[static_cast<size_t>(owner)].clear();
                        sc.memberAddByOwner[static_cast<size_t>(owner)].clear();
                        sc.idegByOwner[static_cast<size_t>(owner)].clear();
                    }
                    for (u32 jj = workBegin; jj < workEnd; ++jj) {
                        const u32 pos = reverse ? (finish - 1u - jj) : (begin + jj);
                        const u32 v = verts[pos];
                        const u32 dst = propActualDst[v];
                        if (dst == NO_MOVE) continue;
                        const u32 src = propSrc[v];
                        sc.memberRemoveByOwner[static_cast<size_t>(src % static_cast<u32>(nt))].push_back(v);
                        sc.memberAddByOwner[static_cast<size_t>(dst % static_cast<u32>(nt))].push_back(v);

                        // Same-color movers are nonadjacent, so no mover's direct
                        // assignment below conflicts with a neighbor delta from
                        // another mover in this batch.
                        internalDeg[v] = propDstCnt[v];
                        if (mergeLegalDirtyScan) {
                            sc.dirtyByOwner[static_cast<size_t>(range_owner(v, nt))]
                                .push_back(v);
                        }
                        for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                            const u32 x = g.adj[e];
                            if (mergeLegalDirtyScan) {
                                sc.dirtyByOwner[
                                    static_cast<size_t>(range_owner(x, nt))]
                                    .push_back(x);
                            }
                            const u32 pc = workPart[x];
                            i32 delta = 0;
                            if (pc == src) --delta;
                            if (pc == dst) ++delta;
                            if (delta != 0)
                                sc.idegByOwner[static_cast<size_t>(x % static_cast<u32>(nt))].push_back({x, delta});
                        }
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                    // Phase 1: source-community owners unlink outgoing vertices.
                    for (int producer = 0; producer < nt; ++producer) {
                        const auto& in = tls[static_cast<size_t>(producer)].memberRemoveByOwner[static_cast<size_t>(tid)];
                        for (u32 v : in) membership_remove_owned(v, propSrc[v]);
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                    // Phase 2: destination-community owners insert incoming vertices.
                    for (int producer = 0; producer < nt; ++producer) {
                        const auto& in = tls[static_cast<size_t>(producer)].memberAddByOwner[static_cast<size_t>(tid)];
                        for (u32 v : in) membership_insert_owned(v, propActualDst[v]);
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                    // Target-vertex owners apply all additive internal-degree deltas;
                    // no atomic writes are needed even when movers share neighbors.
                    for (int producer = 0; producer < nt; ++producer) {
                        const auto& in = tls[static_cast<size_t>(producer)].idegByOwner[static_cast<size_t>(tid)];
                        for (const auto& rec : in) {
                            const i64 z = static_cast<i64>(internalDeg[rec.first]) + rec.second;
                            if (z < 0) throw std::runtime_error("internalDeg underflow in owner reduction");
                            internalDeg[rec.first] = static_cast<u32>(z);
                        }
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                }

                if (legal && legalDynamicMode) {
                    auto emit_dirty = [&](u32 x) {
                        sc.dirtyByOwner[static_cast<size_t>(range_owner(x, nt))].push_back(x);
                    };
                    // A moved vertex changes neighbor-community counts for N(v).
                    if (!mergeLegalDirtyScan) {
                        for (u32 v : sc.movedVerts) {
                            emit_dirty(v);
                            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e)
                                emit_dirty(g.adj[e]);
                        }
                    }
                    // In Legal, community c is a candidate only for representative(c)'s
                    // neighbors. A size/representative change therefore affects exactly
                    // representative(c) U N(representative(c)), not the whole community neighborhood.
                    for (u32 r : sc.changedRepresentatives) {
                        if (r == INVALID) continue;
                        emit_dirty(r);
                        for (u64 e = g.off[r]; e < g.off[r + 1]; ++e) emit_dirty(g.adj[e]);
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                    for (int producer = 0; producer < nt; ++producer) {
                        const auto& in = tls[static_cast<size_t>(producer)].dirtyByOwner[static_cast<size_t>(tid)];
                        for (u32 x : in) {
                            if (legalPending[x]) continue;
                            legalPending[x] = 1;
                            sc.legalPendingByColor[colorOf[x]].push_back(x);
                        }
                    }
#ifdef _OPENMP
#pragma omp barrier
#endif
                }

                for (u32 c : sc.deltaTouched) batchDelta[c] = 0;
#ifdef _OPENMP
#pragma omp barrier
#endif
            }
        }
        return static_cast<u64>(moved);
    }

    void clear_dynamic_legal_queues() {
#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
#else
            const int tid = 0;
#endif
            ThreadScratch& sc = tls[static_cast<size_t>(tid)];
            for (auto& q : sc.legalPendingByColor) {
                for (u32 v : q) legalPending[v] = 0;
                q.clear();
            }
        }
        legalWorkVerts.clear();
    }

    void refresh_dynamic_legal_stats() {
        unsigned long long cnt = 0, edges = 0;
        const i64 slots = static_cast<i64>(tls.size()) * static_cast<i64>(numColors);
#ifdef _OPENMP
#pragma omp parallel for reduction(+:cnt,edges) schedule(static)
#endif
        for (i64 ii = 0; ii < slots; ++ii) {
            const size_t t = static_cast<size_t>(ii / static_cast<i64>(numColors));
            const u32 c = static_cast<u32>(ii % static_cast<i64>(numColors));
            const auto& q = tls[t].legalPendingByColor[c];
            cnt += static_cast<unsigned long long>(q.size());
            u64 e = 0;
            for (u32 v : q) e += g.degree(v);
            edges += e;
        }
        useLegalActive = true;
        legalActiveCount = cnt;
        legalActiveEdges = edges;
    }

    void seed_all_dynamic_legal_pending() {
        clear_dynamic_legal_queues();
#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
            const int nt = omp_get_num_threads();
#else
            const int tid = 0, nt = 1;
#endif
            ThreadScratch& out = tls[static_cast<size_t>(tid)];
            const u32 lo = static_cast<u32>((static_cast<u64>(n) * tid) / nt);
            const u32 hi = static_cast<u32>(
                (static_cast<u64>(n) * (tid + 1)) / nt);
            for (u32 v = lo; v < hi; ++v) {
                legalPending[v] = 1;
                out.legalPendingByColor[colorOf[v]].push_back(v);
            }
        }
        useLegalActive = true;
        legalActiveCount = n;
        legalActiveEdges = g.off[n];
    }

    void seed_dynamic_legal_pending_from_transaction() {
        // Discard only still-pending work from the previous epoch. No O(n) clear.
        clear_dynamic_legal_queues();

        // Conservative full-vs-sparse decision. All terms are nonnegative, so the
        // threshold decision is identical whether summed serially with early exit
        // or in parallel to completion.
        unsigned long long estEdges = 0;
#ifdef _OPENMP
#pragma omp parallel for reduction(+:estEdges) schedule(static)
#endif
        for (i64 pp = 0; pp < static_cast<i64>(tls.size()); ++pp) {
            const ThreadScratch& in = tls[static_cast<size_t>(pp)];
            u64 local = 0;
            for (const auto& rec : in.partUndo) {
                const u32 v = rec.first;
                local += g.degree(v);
                const u32 oldc = rec.second, newc = workPart[v];
                if (oldc != INVALID && workRepresentative[oldc] != INVALID) local += g.degree(workRepresentative[oldc]) + 1;
                if (newc != INVALID && workRepresentative[newc] != INVALID) local += g.degree(workRepresentative[newc]) + 1;
            }
            for (const auto& rec : in.representativeUndo) {
                if (rec.second != INVALID) local += g.degree(rec.second) + 1;
                const u32 nr = workRepresentative[rec.first];
                if (nr != INVALID) local += g.degree(nr) + 1;
            }
            estEdges += local;
        }

        if (estEdges >= g.off[n] / 2) {
            seed_all_dynamic_legal_pending();
            return;
        }

#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
            const int nt = omp_get_num_threads();
#else
            const int tid = 0, nt = 1;
#endif
            ThreadScratch& out = tls[static_cast<size_t>(tid)];
            for (int owner = 0; owner < nt; ++owner)
                out.dirtyByOwner[static_cast<size_t>(owner)].clear();
            auto emit = [&](u32 x) {
                if (x == INVALID) return;
                out.dirtyByOwner[static_cast<size_t>(range_owner(x, nt))].push_back(x);
            };
            auto emit_source = [&](u32 x) {
                if (x == INVALID) return;
                emit(x);
                for (u64 e = g.off[x]; e < g.off[x + 1]; ++e) emit(g.adj[e]);
            };

            // Each producer handles its own transaction log; target ownership is
            // only needed for deduplicating legalPending[x] without atomics.
            const ThreadScratch& in = tls[static_cast<size_t>(tid)];
            for (const auto& rec : in.partUndo) {
                const u32 v = rec.first;
                emit_source(v);
                const u32 oldc = rec.second, newc = workPart[v];
                if (oldc != INVALID) emit_source(workRepresentative[oldc]);
                if (newc != INVALID) emit_source(workRepresentative[newc]);
            }
            for (const auto& rec : in.representativeUndo) {
                emit_source(rec.second);
                emit_source(workRepresentative[rec.first]);
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            u64 localCnt = 0, localEdges = 0;
            for (int producer = 0; producer < nt; ++producer) {
                const auto& q = tls[static_cast<size_t>(producer)].dirtyByOwner[static_cast<size_t>(tid)];
                for (u32 x : q) {
                    if (legalPending[x]) continue;
                    legalPending[x] = 1;
                    out.legalPendingByColor[colorOf[x]].push_back(x);
                    ++localCnt;
                    localEdges += g.degree(x);
                }
            }
            threadSingletonCount[static_cast<size_t>(tid)] = localCnt;
            threadSingletonBase[static_cast<size_t>(tid)] = localEdges;
        }

        u64 cnt = 0, edges = 0;
        for (size_t t = 0; t < tls.size(); ++t) {
            cnt += threadSingletonCount[t];
            edges += threadSingletonBase[t];
        }
        useLegalActive = true;
        legalActiveCount = cnt;
        legalActiveEdges = edges;
    }

    void disable_legal_frontier() {
        useLegalActive = false;
        legalActiveCount = n;
        legalActiveEdges = g.off[n];
    }

    void project_to_stars_cached(bool allCommunities) {
        if (!internalReady) throw std::runtime_error("cached Project without internal-degree cache");
        collect_changed_communities_from_txn(allCommunities);
        const double t0 = sec_now();
        if (changedComms.empty()) {
            lastPeeled = 0;
            return;
        }

        for (auto& sc : tls) sc.peeledLocal.clear();
        unsigned long long peeledInternal = 0;
        long long deltaP64 = 0;

#ifdef _OPENMP
#pragma omp parallel reduction(+:peeledInternal,deltaP64)
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
#else
            const int tid = 0;
#endif
            ThreadScratch& sc = tls[static_cast<size_t>(tid)];
#ifdef _OPENMP
#pragma omp for schedule(dynamic, 64)
#endif
            for (i64 ii = 0; ii < static_cast<i64>(changedComms.size()); ++ii) {
                const u32 c = changedComms[static_cast<size_t>(ii)];
                const u32 oldSize = workSize[c];
                if (oldSize == 0) {
                    if (workRepresentative[c] != INVALID) {
                        record_representative_before_change(sc, c);
                        workRepresentative[c] = INVALID;
                    }
                    continue;
                }

                u32 r = INVALID, best = 0;
                for (u32 v = memberHead[c]; v != INVALID; v = memberNext[v]) {
                    keep[v] = 0;
                    u32 d = 0;
                    for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                        const u32 u = g.adj[e];
                        d += workPart[u] == c && g.source_can_represent(e);
                    }
                    if (r == INVALID || d > best ||
                        (d == best && v < r)) {
                        r = v; best = d;
                    }
                }
                if (r == INVALID) throw std::runtime_error("membership list/size mismatch in Project");
                projRepresentative[c] = r;
                projBestDeg[c] = best;
                keep[r] = 1;
                for (u64 e = g.off[r]; e < g.off[r + 1]; ++e) {
                    const u32 u = g.adj[e];
                    if (workPart[u] == c && g.source_can_represent(e)) {
                        keep[u] = 1;
                    }
                }

                const u32 keptSize = 1u + best;
                deltaP64 += static_cast<long long>(static_cast<u64>(keptSize) * (keptSize - 1) / 2)
                          - static_cast<long long>(static_cast<u64>(oldSize) * (oldSize - 1) / 2);
                workSize[c] = keptSize;
                if (workRepresentative[c] != r) {
                    record_representative_before_change(sc, c);
                    workRepresentative[c] = r;
                }

                for (u32 v = memberHead[c]; v != INVALID; v = memberNext[v]) {
                    if (!keep[v]) {
                        sc.peeledLocal.push_back(v);
                        peeledInternal += internalDeg[v];
                    }
                }
            }
        }

        // Deterministic sparse compaction: route only peeled vertices to a
        // contiguous vertex-ID-range owner. Owners sort independently; owner-range
        // concatenation is therefore exactly the old global ascending-ID order,
        // without scanning untouched vertices or performing a global sort.
        peeledVerts.clear();
#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
            const int nt = omp_get_num_threads();
#else
            const int tid = 0, nt = 1;
#endif
            ThreadScratch& out = tls[static_cast<size_t>(tid)];
            out.peeledOwned.clear();
            for (int owner = 0; owner < nt; ++owner)
                out.peeledByOwner[static_cast<size_t>(owner)].clear();
            for (u32 v : out.peeledLocal)
                out.peeledByOwner[static_cast<size_t>(range_owner(v, nt))].push_back(v);
#ifdef _OPENMP
#pragma omp barrier
#endif
            for (int producer = 0; producer < nt; ++producer) {
                const auto& q = tls[static_cast<size_t>(producer)].peeledByOwner[static_cast<size_t>(tid)];
                out.peeledOwned.insert(out.peeledOwned.end(), q.begin(), q.end());
            }
            std::sort(out.peeledOwned.begin(), out.peeledOwned.end());
            threadSingletonCount[static_cast<size_t>(tid)] = static_cast<u64>(out.peeledOwned.size());
#ifdef _OPENMP
#pragma omp barrier
#pragma omp single
#endif
            {
                u64 total = 0;
                for (int t = 0; t < nt; ++t) {
                    threadSingletonBase[static_cast<size_t>(t)] = total;
                    total += threadSingletonCount[static_cast<size_t>(t)];
                }
                peeledVerts.resize(static_cast<size_t>(total));
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            const size_t base = static_cast<size_t>(threadSingletonBase[static_cast<size_t>(tid)]);
            std::copy(out.peeledOwned.begin(), out.peeledOwned.end(), peeledVerts.begin() + base);
        }
        lastPeeled = static_cast<u64>(peeledVerts.size());

        unsigned long long peeledPPEdges = 0;
#ifdef _OPENMP
#pragma omp parallel for reduction(+:peeledPPEdges) schedule(dynamic, 512)
#endif
        for (i64 ii = 0; ii < static_cast<i64>(peeledVerts.size()); ++ii) {
            const u32 v = peeledVerts[static_cast<size_t>(ii)];
            const u32 c = workPart[v];
            u64 local = 0;
            for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                const u32 u = g.adj[e];
                local += (u > v && !keep[u] && workPart[u] == c);
            }
            peeledPPEdges += local;
        }
        const u64 removedT = static_cast<u64>(peeledInternal) - static_cast<u64>(peeledPPEdges);
        if (removedT > workAudit.T) throw std::runtime_error("cached projection T underflow");
        workAudit.T -= removedT;
        workAudit.P = static_cast<u64>(static_cast<i128>(workAudit.P) + static_cast<i128>(deltaP64));
        if (freeIds.size() < peeledVerts.size()) throw std::runtime_error("cached projection free-id exhaustion");
        const size_t freeBase = freeIds.size() - peeledVerts.size();
        std::vector<u32> oldComms(peeledVerts.size()), newComms(peeledVerts.size());
#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
#else
            const int tid = 0;
#endif
            ThreadScratch& sc = tls[static_cast<size_t>(tid)];
#ifdef _OPENMP
#pragma omp for schedule(static)
#endif
            for (i64 ii = 0; ii < static_cast<i64>(peeledVerts.size()); ++ii) {
                const size_t i = static_cast<size_t>(ii);
                const u32 v = peeledVerts[i];
                const u32 oldc = workPart[v];
                const u32 newc = freeIds[freeIds.size() - 1 - i];
                oldComms[i] = oldc;
                newComms[i] = newc;
                propSrc[v] = oldc;
                propActualDst[v] = newc;
                record_part_before_change(sc, v);
                record_representative_before_change(sc, newc);
                workPart[v] = newc;
                workSize[newc] = 1;
                workRepresentative[newc] = v;
                internalDeg[v] = 0;
            }
        }
        // Forced Project moves use the same owner-computes state-update model as
        // Relax/Legal: source owners unlink, destination owners insert, and target
        // vertex owners apply additive internal-degree deltas.
#ifdef _OPENMP
#pragma omp parallel
#endif
        {
#ifdef _OPENMP
            const int tid = omp_get_thread_num();
            const int nt = omp_get_num_threads();
#else
            const int tid = 0, nt = 1;
#endif
            ThreadScratch& sc = tls[static_cast<size_t>(tid)];
            for (int owner = 0; owner < nt; ++owner) {
                sc.memberRemoveByOwner[static_cast<size_t>(owner)].clear();
                sc.memberAddByOwner[static_cast<size_t>(owner)].clear();
                sc.idegByOwner[static_cast<size_t>(owner)].clear();
            }
#ifdef _OPENMP
#pragma omp for schedule(static)
#endif
            for (i64 ii = 0; ii < static_cast<i64>(peeledVerts.size()); ++ii) {
                const size_t i = static_cast<size_t>(ii);
                const u32 v = peeledVerts[i];
                const u32 oldc = oldComms[i], newc = newComms[i];
                sc.memberRemoveByOwner[static_cast<size_t>(oldc % static_cast<u32>(nt))].push_back(v);
                sc.memberAddByOwner[static_cast<size_t>(newc % static_cast<u32>(nt))].push_back(v);
                for (u64 e = g.off[v]; e < g.off[v + 1]; ++e) {
                    const u32 x = g.adj[e];
                    if (workPart[x] == oldc)
                        sc.idegByOwner[static_cast<size_t>(x % static_cast<u32>(nt))].push_back({x, -1});
                }
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            for (int producer = 0; producer < nt; ++producer) {
                const auto& in = tls[static_cast<size_t>(producer)].memberRemoveByOwner[static_cast<size_t>(tid)];
                for (u32 v : in) membership_remove_owned(v, propSrc[v]);
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            for (int producer = 0; producer < nt; ++producer) {
                const auto& in = tls[static_cast<size_t>(producer)].memberAddByOwner[static_cast<size_t>(tid)];
                for (u32 v : in) membership_insert_owned(v, workPart[v]);
            }
#ifdef _OPENMP
#pragma omp barrier
#endif
            for (int producer = 0; producer < nt; ++producer) {
                const auto& in = tls[static_cast<size_t>(producer)].idegByOwner[static_cast<size_t>(tid)];
                for (const auto& rec : in) {
                    const i64 z = static_cast<i64>(internalDeg[rec.first]) + rec.second;
                    if (z < 0) throw std::runtime_error("internalDeg underflow in Project owner reduction");
                    internalDeg[rec.first] = static_cast<u32>(z);
                }
            }
        }
        txn_free_shrink(freeBase);

        disable_legal_frontier();
        if (verbose) std::cerr << "    cached_project changed_comms=" << changedComms.size()
                  << " peeled=" << peeledVerts.size()
                  << " time=" << (sec_now()-t0) << " s\n";
    }


};

static u64 parse_u64_token(std::string_view text, const char* what) {
    if (text.empty()) throw std::runtime_error(std::string("empty ") + what);
    u128 value = 0;
    for (char ch : text) {
        if (ch < '0' || ch > '9')
            throw std::runtime_error(std::string("invalid ") + what + ": " +
                                     std::string(text));
        value = value * 10u + static_cast<unsigned>(ch - '0');
        if (value > std::numeric_limits<u64>::max())
            throw std::runtime_error(std::string(what) + " exceeds uint64");
    }
    return static_cast<u64>(value);
}

static LambdaRatio parse_lambda_ratio(std::string_view text) {
    const size_t slash = text.find('/');
    u64 numerator = 0;
    u64 denominator = 1;
    if (slash == std::string_view::npos) {
        numerator = parse_u64_token(text, "lambda numerator");
    } else {
        if (text.find('/', slash + 1) != std::string_view::npos)
            throw std::runtime_error("lambda must be 0, 1, or A/B");
        numerator = parse_u64_token(text.substr(0, slash), "lambda numerator");
        denominator = parse_u64_token(
            text.substr(slash + 1), "lambda denominator");
    }
    if (denominator == 0 || numerator > denominator)
        throw std::runtime_error("lambda must satisfy 0 <= A <= B in A/B");
    const u64 divisor = std::gcd(numerator, denominator);
    return LambdaRatio{numerator / divisor, denominator / divisor};
}

